class WafDetector:
    """Detects WAFs and recommends adaptive evasion strategies."""

    def __init__(self):
        pass

    def inspect_response(
        self,
        status_code: int,
        headers: Dict[str, str],
        body: str = "",
        cookies: Optional[str] = None
    ) -> Dict[str, Any]:
        """Detect presence of any known WAF/CDN from HTTP response characteristics."""
        h_lower = {k.lower(): str(v).lower() for k, v in headers.items()}
        server_val = h_lower.get("server", "")
        body_lower = (body or "").lower()
        cookie_str = (cookies or h_lower.get("set-cookie", "")).lower()

        detected = []

        for waf_name, sigs in WAF_SIGNATURES.items():
            matched_reasons = []

            # Check Headers
            for h in sigs["headers"]:
                if ":" in h:
                    hk, hv = h.split(":", 1)
                    if hk.strip() in h_lower and hv.strip() in h_lower[hk.strip()]:
                        matched_reasons.append(f"Header '{h}' matched")
                elif h in h_lower:
                    matched_reasons.append(f"Header '{h}' present")

            # Check Server header
            for s in sigs["server"]:
                if s in server_val:
                    matched_reasons.append(f"Server header '{server_val}' matched '{s}'")

            # Check Cookies
            for c in sigs["cookies"]:
                if c in cookie_str:
                    matched_reasons.append(f"Cookie '{c}' present")

            # Check Body
            for b in sigs["body"]:
                if b.lower() in body_lower:
                    matched_reasons.append(f"Body signature '{b}' found")

            if matched_reasons:
                detected.append({
                    "waf": waf_name,
                    "confidence": "HIGH" if len(matched_reasons) >= 2 or any("Body" in r for r in matched_reasons) else "MEDIUM",
                    "reasons": matched_reasons,
                })

        # Calculate Adaptive Evasion Parameters
        is_waf_present = len(detected) > 0
        evasion_config = {
            "waf_detected": is_waf_present,
            "detected_wafs": detected,
            "recommended_delay": 0.8 if is_waf_present else 0.2,
            "recommended_max_requests": 60 if is_waf_present else 150,
            "use_random_agent": is_waf_present,
            "evasion_notes": (
                f"WAF detected ({', '.join(d['waf'] for d in detected)}). "
                "Enforce rate-limiting pacing (0.8s delay) and avoid brute-force fuzzing."
                if is_waf_present else "No upstream WAF detected. Standard operational pacing active."
            )
        }

        return evasion_config
